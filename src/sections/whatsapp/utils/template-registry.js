export function reconstructTemplateText(templateName, templateComponents) {
  const template = TEMPLATE_REGISTRY[templateName];
  if (!template) return `[Template: ${templateName}]`;

  let text = template.body;
  if (!templateComponents) return text;

  const bodyComponent = templateComponents.find((c) => c.type === 'body');
  if (bodyComponent && bodyComponent.parameters) {
    bodyComponent.parameters.forEach((param, index) => {
      let val = '';
      if (param.type === 'text') val = param.text;
      if (param.type === 'currency') val = param.currency?.fallback_value || param.currency?.amount || '';
      if (param.type === 'date_time') val = param.date_time?.fallback_value || '';

      const strVal = String(val ?? '');
      const placeholder = `{{${index + 1}}}`;

      // Handle currency symbol collision (e.g. ₹{{5}} when val is already formatted as "₹24,560")
      if (text.includes(`₹${placeholder}`) && strVal.startsWith('₹')) {
        text = text.replace(`₹${placeholder}`, strVal);
      } else {
        text = text.replace(placeholder, strVal);
      }
    });
  }

  return text;
}

export function getTemplateButtons(templateName) {
  const template = TEMPLATE_REGISTRY[templateName];
  if (!template || !template.buttons) return [];
  return template.buttons;
}

export function getTemplateFooter(templateName) {
  const template = TEMPLATE_REGISTRY[templateName];
  if (!template || !template.footer) return '';
  return template.footer;
}

export function getTemplateSnippet(templateName) {
  const template = TEMPLATE_REGISTRY[templateName];
  if (!template) return `Template: ${templateName}`;
  return template.snippetPrefix ? `${template.snippetPrefix}` : `Template: ${templateName}`;
}
